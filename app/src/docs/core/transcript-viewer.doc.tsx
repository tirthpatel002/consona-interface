import React, { useEffect, useState } from 'react'
import {
  TranscriptViewer,
  type TranscriptAlignment,
} from '@consona/interface'
import type { ComponentDocSpec } from '../types'

const DEMO_AUDIO = '/sounds/transcript-viewer/transcript-viewer-audio.mp3'

function TranscriptViewerDemo() {
  const [transcriptAlignment, setTranscriptAlignment] = useState<TranscriptAlignment | null>(null)

  useEffect(() => {
    fetch('/sounds/transcript-viewer/transcript-viewer-alignment.json')
      .then((res) => res.json())
      .then((data: TranscriptAlignment) => setTranscriptAlignment(data))
      .catch(() => {
        setTranscriptAlignment({
          characters: [],
          characterStartTimesSeconds: [],
          characterEndTimesSeconds: [],
          words: [
            { word: 'Consona', startTime: 0.0, endTime: 0.8 },
            { word: 'allows', startTime: 0.85, endTime: 1.2 },
            { word: 'you', startTime: 1.25, endTime: 1.45 },
            { word: 'to', startTime: 1.5, endTime: 1.65 },
            { word: 'generate', startTime: 1.7, endTime: 2.3 },
            { word: 'audio', startTime: 2.35, endTime: 2.8 },
            { word: 'transcripts', startTime: 2.85, endTime: 3.6 },
            { word: 'with', startTime: 3.65, endTime: 3.85 },
            { word: 'perfect', startTime: 3.9, endTime: 4.4 },
            { word: 'word-level', startTime: 4.45, endTime: 5.1 },
            { word: 'synchronization.', startTime: 5.15, endTime: 6.2 },
          ],
        })
      })
  }, [])

  return (
    <div className="w-full max-w-xl">
      {transcriptAlignment ? (
        <TranscriptViewer
          src={DEMO_AUDIO}
          transcript={transcriptAlignment}
        />
      ) : (
        <div className="flex h-32 items-center justify-center rounded-2xl border border-border/50 bg-card/60 text-xs text-muted-fg">
          Loading transcript alignment...
        </div>
      )}
    </div>
  )
}

export const transcriptViewerDoc: ComponentDocSpec = {
  id: 'transcript-viewer',
  name: 'Transcript Viewer',
  component: TranscriptViewer,
  summary:
    'Real-time synchronized interactive speech transcript viewer with word-level highlight, seek-on-click, search filter, and full audio playback transport.  Demo audio generated by ElevenLabs.',
  subcomponents: [
    'TranscriptViewer',
    'TranscriptViewer.Header',
    'TranscriptViewer.Body',
    'TranscriptViewer.Word',
    'TranscriptViewer.Search',
    'TranscriptViewer.Transport',
  ],
  playground: {
    defaultProps: {},
    controls: [],
    render: () => <TranscriptViewerDemo />,
  },
  examples: [
    {
      title: 'Synchronized Transcript with Word Highlighting',
      description:
        'Click on any word to seek the audio directly to that exact millisecond timestamp. Current spoken word pulses with active focus.',
      render: () => <TranscriptViewerDemo />,
    },
  ],
}
